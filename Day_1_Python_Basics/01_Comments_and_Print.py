# Comments make code easier to understand.


# ============================================================
# 2. PRINT STATEMENT
# ============================================================

# print() is used to display output on the screen.

print("Hello, Python!")

print("Welcome to AI Bootcamp!")

print("Python is easy to learn.")


# ============================================================
# 3. PRINTING NUMBERS
# ============================================================

print(10)

print(100)

print(3.14)


# ============================================================
# 4. PRINTING MULTIPLE VALUES
# ============================================================

name = "Jaya"
age = 25

print(name, age)


# ============================================================
# 5. PRINTING TEXT AND NUMBERS TOGETHER
# ============================================================

print("My name is", name)

print("My age is", age)


# ============================================================
# 6. USING SEPARATOR
# ============================================================

# sep= controls how multiple values are separated.

print("Python", "Java", "C++")

print("Python", "Java", "C++", sep=" | ")

print("2026", "08", "11", sep="-")


# ============================================================
# 7. USING END
# ============================================================

# By default, print() moves to a new line.
# end= allows us to change that behavior.

print("Hello", end=" ")
print("World")


print("Python", end=" ---> ")
print("Programming")


# ============================================================
# 8. MULTIPLE PRINT STATEMENTS
# ============================================================

print("AI")
print("Machine Learning")
print("Generative AI")
print("FastAPI")


# ============================================================
# 9. PRINTING AN EXPRESSION
# ============================================================

print(10 + 20)

print(100 - 50)

print(10 * 5)

print(100 / 4)


